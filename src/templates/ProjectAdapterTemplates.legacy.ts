export function runWrapperTemplate() {
    return [
        "# Generated by SimpleExperiment.",
        "# 用于不改训练代码时捕获 stdout/stderr，并在命令结束后生成标准输出文件。",
        "",
        "from __future__ import annotations",
        "",
        "import argparse",
        "import json",
        "import shlex",
        "import subprocess",
        "import sys",
        "from pathlib import Path",
        "",
        "try:",
        "    from .result_writer import collect_outputs",
        "except Exception:",
        "    from result_writer import collect_outputs",
        "",
        "def main():",
        "    parser = argparse.ArgumentParser(description=\"SimpleExperiment 实验运行包装器\")",
        "    parser.add_argument(\"--output-dir\", required=True)",
        "    parser.add_argument(\"--context-json\", default=\"{}\")",
        "    parser.add_argument(\"command\", nargs=argparse.REMAINDER)",
        "    args = parser.parse_args()",
        "    if not args.command:",
        "        raise SystemExit(\"缺少要执行的训练或测试命令。\")",
        "    output_dir = Path(args.output_dir)",
        "    output_dir.mkdir(parents=True, exist_ok=True)",
        "    command = args.command[1:] if args.command[:1] == [\"--\"] else args.command",
        "    import threading",
        "    stdout_path = output_dir / \"stdout.log\"",
        "    stderr_path = output_dir / \"stderr.log\"",
        "    child_env = os.environ.copy()",
        "    child_env[\"PYTHONUNBUFFERED\"] = \"1\"",
        "    proc = subprocess.Popen(command, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, bufsize=1, env=child_env)",
        "    stdout_chunks: list[str] = []",
        "    stderr_chunks: list[str] = []",
        "    def _pump(pipe, path, chunks, to_stdout):",
        "        try:",
        "            with open(path, \"a\", encoding=\"utf-8\") as f:",
        "                for line in iter(pipe.readline, \"\"):",
        "                    if to_stdout:",
        "                        sys.stdout.write(line); sys.stdout.flush()",
        "                    else:",
        "                        sys.stderr.write(line); sys.stderr.flush()",
        "                    f.write(line); f.flush()",
        "                    chunks.append(line)",
        "        except Exception:",
        "            pass",
        "        finally:",
        "            try: pipe.close()",
        "            except Exception: pass",
        "    t_out = threading.Thread(target=_pump, args=(proc.stdout, stdout_path, stdout_chunks, True), daemon=True)",
        "    t_err = threading.Thread(target=_pump, args=(proc.stderr, stderr_path, stderr_chunks, False), daemon=True)",
        "    t_out.start(); t_err.start()",
        "    proc.wait()",
        "    t_out.join(); t_err.join()",
        "    stdout_text = \"\".join(stdout_chunks)",
        "    stderr_text = \"\".join(stderr_chunks)",
        "    # 兼容兜底：若线程未捕获（空），尝试读取已有文件",
        "    if not stdout_text and stdout_path.is_file():",
        "        try: stdout_text = stdout_path.read_text(encoding=\"utf-8\", errors=\"ignore\")",
        "        except Exception: pass",
        "    if not stderr_text and stderr_path.is_file():",
        "        try: stderr_text = stderr_path.read_text(encoding=\"utf-8\", errors=\"ignore\")",
        "        except Exception: pass",
        "    context = json.loads(args.context_json or \"{}\")",
        "    context.setdefault(\"command\", \" \".join(shlex.quote(item) for item in command))",
        "    collect_outputs(output_dir, context=context, stdout_text=stdout_text, stderr_text=stderr_text)",
        "    sys.exit(proc.returncode)",

        "",
        "if __name__ == \"__main__\":",
        "    main()",
        "",
    ].join("\n");
}
